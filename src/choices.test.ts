import { describe, expect, test } from "bun:test";
import { choicesOf } from "./model";

// 2026-11-22 に本人のスクショで出た誤り。見出しの「**着手前に1つだけ決めてほしい**」をボタンにし、40字を超える選択肢2を黙って落とした
const SHOT = `結論: できる。前はチャットから答えられたけど、11/21 に ccn を外したときにその口も消えて、今はアプリが立てたセッションは全部「ターミナルで答えて」になってる。

**やり方の案**
- 質問の中身: transcript にある AskUserQuestion の tool_use の input から読む。hook の形を変えないので、安定版に影響しない。
- 答えの届け方: switch.rs の /model と同じで、CLI のダイアログに人が打つのと同じキーを PTY に書く。

**着手前に1つだけ決めてほしい**
範囲はどこまでにする？
1. 質問（AskUserQuestion）だけ
2. 質問に加えて、道具の承認（許可／常に許可／拒否）と計画の確認（ExitPlanMode）も。フォームはもうあるので、足すのはキーの対応表と実機での確認くらい

見積もり: ロジック＋UIの実装で、中央値18分・p90は1.8時間くらい。長引きそうなのは、CLI のダイアログのキー操作を実機で確かめるところ。`;

// 2026-11-22 に本人が「普通に変じゃない？」と指した誤り。報告の箇条書き（触ってないもの）を、はい/いいえで答える最後の問いの選択肢にした
const REPORT = `**触ってないもの**
- 孫の札を選んで拡大したとき、余白が 16px になったことで枠の端で切れるかは見てない
- カードを並べる計算の余白（10、18）はグリッドの外のまま。枠の入れ子もそのまま

動いてる子は、「読めない」表示の子（\`5d1ea311\`）の1体だけになった。それが終わったら、#162・#164・#165 とまとめて /Applications のアプリを入れ替える？`;

describe("choicesOf", () => {
  test("報告の箇条書きを、はい/いいえの問いの選択肢にしない（2026-11-22 の返事）", () => {
    expect(choicesOf(REPORT)).toEqual([]);
  });
  test("選ぶ言い方でない問いの前の箇条書きは選択肢にしない", () => {
    expect(choicesOf("- A\n- B\n\n進めていい？")).toEqual([]);
  });
  test("問いの前の箇条書きは、選ぶ言い方の問いのときだけ選択肢にする", () => {
    expect(choicesOf("- A案\n- B案\nどちらにする？")).toEqual(["A案", "B案"]);
    expect(choicesOf("- A案\n- B案\n\nどの案がいい？")).toEqual(["A案", "B案"]);
  });
  test("太字の見出しを選択肢にせず、長い選択肢も落とさない（2026-11-22 のスクショ）", () => {
    expect(choicesOf(SHOT)).toEqual([
      "質問（AskUserQuestion）だけ",
      "質問に加えて、道具の承認（許可／常に許可／拒否）と計画の確認（ExitPlanMode）も。フォームはもうあるので、足すのはキーの対応表と実機での確認くらい",
    ]);
  });
  test("問いの後ろの箇条書きを選ぶ", () => {
    expect(choicesOf("どっちにする？\n- A案\n- B案")).toEqual(["A案", "B案"]);
  });
  test("問いの前の箇条書きでもよい", () => {
    expect(choicesOf("1. 赤\n2. 青\n\nどっちにする？")).toEqual(["赤", "青"]);
  });
  test("問いが無ければ出さない", () => {
    expect(choicesOf("やったこと\n- A\n- B")).toEqual([]);
  });
  test("太字の行は箇条書きではない", () => {
    expect(choicesOf("**大事**\n**注意**\nどうする？")).toEqual([]);
  });
  test("中の太字の印は外す", () => {
    expect(choicesOf("どれ？\n1. **速い**ほう\n2. 安いほう")).toEqual(["速いほう", "安いほう"]);
  });
  test("1件だけ、または6件以上は出さない", () => {
    expect(choicesOf("どれ？\n- A")).toEqual([]);
    expect(choicesOf("どれ？\n- A\n- B\n- C\n- D\n- E\n- F")).toEqual([]);
  });
});
